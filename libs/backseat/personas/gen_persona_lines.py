#!/usr/bin/env python3
"""Builds ../persona_lines_data.cpp from the persona line files next to this script.

Each file starts with "== <persona id>", then "[key]" blocks of "<tier> <line>" rows (tier 0, 1 or 2;
everything after the first space is the line, so instruction.prefix/suffix keep their spaces).
"#" rows are comments. Keys must already exist in lines_data.cpp, and a persona line may only use
{placeholders} the default lines for that key use. Run: python3 gen_persona_lines.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'persona_lines_data.cpp')
DEFAULT = os.path.join(HERE, '..', 'lines_data.cpp')
PERSONAS = [('melancholy', 'Melancholy'), ('proud', 'Proud')]


def default_placeholders():
    src = open(DEFAULT, encoding='utf-8').read()
    parts = re.split(r'\n    \{"([^"]+)",\n', src)
    return {parts[i]: {p.lower() for p in re.findall(r'\{([A-Za-z_]+)\}', parts[i + 1])}
            for i in range(1, len(parts), 2)}


def parse(path, known):
    persona, key, table, errors = None, None, {}, []
    for n, row in enumerate(open(path, encoding='utf-8').read().split('\n'), 1):
        if not row.strip() or row.startswith('#'):
            continue
        if row.startswith('== '):
            persona = row[3:].strip()
        elif row.startswith('['):
            key = row.strip()[1:-1]
            if key not in known:
                errors.append(f'{path}:{n}: unknown key {key}')
            table.setdefault(key, [[], [], []])
        else:
            tier, line = row[0], row[2:]
            if tier not in '012' or row[1] != ' ' or not line.strip():
                errors.append(f'{path}:{n}: bad row {row!r}')
                continue
            extra = {p.lower() for p in re.findall(r'\{([A-Za-z_]+)\}', line)} - known.get(key, set())
            if extra and key in known and key != 'persona.leave':
                errors.append(f'{path}:{n}: {key} has no {sorted(extra)}')
            table[key][int(tier)].append(line)
    for key, tiers in table.items():
        if not tiers[0]:
            errors.append(f'{path}: {key} has no tier 0 lines')
    return persona, table, errors


def cpp(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    known = default_placeholders()
    known['persona.leave'] = set()
    out = ['// Generated by personas/gen_persona_lines.py from personas/*.txt. Do not edit by hand.',
           '#include "backseat/persona_lines_data.hpp"', '', 'namespace backseat', '{']
    errors = []
    for pid, fn in PERSONAS:
        persona, table, errs = parse(os.path.join(HERE, pid + '.txt'), known)
        errors += errs
        if persona != pid:
            errors.append(f'{pid}.txt: header says {persona}')
        out += [f'LineTable const & {fn}LineData()', '{', '  static LineTable const table = {']
        for key in sorted(table):
            out.append(f'    {{{cpp(key)},')
            out.append('     {{')
            for tier in table[key]:
                out.append('       {' + ',\n        '.join(cpp(l) for l in tier) + '},')
            out.append('     }}},')
        out += ['  };', '  return table;', '}', '']
    out += ['}  // namespace backseat', '']
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        sys.exit(1)
    open(OUT, 'w', encoding='utf-8').write('\n'.join(out))
    print('wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
